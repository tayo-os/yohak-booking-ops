const fs=require('fs'),vm=require('vm'),assert=require('assert/strict');
const ctx=vm.createContext({Date});
vm.runInContext(fs.readFileSync(__dirname+'/BookingOps.gs','utf8'),ctx);
const guest=(n,status='ACTIVE')=>({ref:'TEST-BOOKING',number:n,status,row:n+3});
const normalize=x=>JSON.parse(JSON.stringify(x));
assert.deepEqual(normalize(ctx.yohakPlanSlots_('TEST-BOOKING',4,[guest(1),guest(2)])),{missing:[3,4],excess:[],review:[]});
assert.deepEqual(normalize(ctx.yohakPlanSlots_('TEST-BOOKING',2,[guest(1),guest(2),guest(3),guest(4)])),{missing:[],excess:[6,7],review:[]});
assert.deepEqual(normalize(ctx.yohakPlanSlots_('TEST-BOOKING',2,[guest(1),guest(2,'CANCELLED')])),{missing:[],excess:[],review:[2]});
assert.deepEqual(normalize(ctx.yohakPlanSlots_('TEST-BOOKING',2,[guest(1),guest(2)])),{missing:[],excess:[],review:[]});
assert.throws(()=>ctx.yohakPlanSlots_('TEST-BOOKING',2,[guest(1),guest(1)]),/Duplicate/);
assert.throws(()=>ctx.yohakPlanSlots_('TEST-BOOKING',2.5,[]),/Invalid/);
assert.throws(()=>ctx.yohakPlanSlots_('TEST-BOOKING',0,[]),/Invalid/);
const now=new Date('2026-10-06T12:00:00+08:00'),before=new Date('2026-10-04T12:00:00+08:00');
